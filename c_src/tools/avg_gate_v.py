"""GATE V - c_src/avg.c vs ../disasm/vrender.py, picture by picture.

  python tools/avg_gate_v.py

Drives the whole check:
  1. Reads ../disasm/build/vector_tables.json ("avg_pictures": HORIZN, MTNS,
     MTN0-7, XCROSS, XCROS1, RDRING, TSYMBL, TANKS, CRACKS, CRACK0-7, EXPIC,
     HATCH, CIRCLE, CPYRIT, PNTNT; "vgan_characters": the 37 VGAN letters/
     digits) and writes tests/avg_shapes_index.txt (NAME ADDRHEX per line) -
     the address list always comes from the generated symbol data, never
     hand-transcribed (see c_src/tests/avgshapes.c's own header).
  2. Runs tests/avgshapes.exe (must already be built - build_avg.bat) over
     that index and the same 64K ROM image ../disasm/avg.py loads, producing
     tests/avg_out/avg_shapes.txt.
  3. For every (name, addr), independently renders the reference with
     ../disasm/vrender.py's walk() (the model ../disasm/emit_shapes.py uses
     for bzone_shapes.html) and compares segment-for-segment: identical
     (x0, y0, x1, y1, intensity) in Q15, same segment count.  The C side's
     clip-window column is not compared - vrender.py does not model the STAT
     clip window (see c_src/avg.h "CLIP WINDOW"), so Gate V is scoped to
     geometry/intensity, exactly as the milestone brief asks.

Exit 0 and "GATE V: PASS" iff every picture/character matches; otherwise
prints every mismatching segment (for manual, evidence-based resolution -
this script edits nothing under ../disasm) and exits 1.
"""
import os
import subprocess
import sys
import json

HERE = os.path.dirname(os.path.abspath(__file__))
CSRC = os.path.dirname(HERE)
ROOT = os.path.dirname(CSRC)
DISASM = os.path.join(ROOT, "disasm")
sys.path.insert(0, DISASM)
import avg, vrender  # noqa: E402

VECTOR_TABLES = os.path.join(DISASM, "build", "vector_tables.json")
ROM_IMAGE = os.path.join(DISASM, "_survey", "roms_extracted", "bzone_cpu64k.bin")
INDEX_PATH = os.path.join(CSRC, "tests", "avg_shapes_index.txt")
OUT_PATH = os.path.join(CSRC, "tests", "avg_out", "avg_shapes.txt")
EXE_PATH = os.path.join(CSRC, "tests", "avgshapes.exe")

MAX_OPS = 4000  # vrender.MAX_STEPS - must match tests/avgshapes.c's cfg.max_ops


def clean(name):
    return name.replace(".", "_").replace("$", "S_")


def load_entries():
    """-> [(name, addr)] from vector_tables.json: every avg_pictures entry,
    then every vgan_characters entry, in file order (deterministic)."""
    vt = json.load(open(VECTOR_TABLES, encoding="utf-8"))
    entries = []
    for p in vt["avg_pictures"]:
        entries.append((clean(p["name"]), int(p["addr"][1:], 16)))
    for c in vt["vgan_characters"]:
        entries.append((clean(c["name"]), int(c["addr"][1:], 16)))
    return entries


def write_index(entries, path):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", newline="\n") as f:
        f.write("# GENERATED by c_src/tools/avg_gate_v.py from "
                 "../disasm/build/vector_tables.json - NAME ADDR(hex)\n")
        for name, addr in entries:
            f.write("%s %04X\n" % (name, addr))


def run_avgshapes():
    if not os.path.exists(EXE_PATH):
        print("tests\\avgshapes.exe not found - run build_avg.bat first")
        return False
    os.makedirs(os.path.join(CSRC, "tests", "avg_out"), exist_ok=True)
    r = subprocess.run(
        [EXE_PATH, "tests\\avg_shapes_index.txt",
         "..\\disasm\\_survey\\roms_extracted\\bzone_cpu64k.bin",
         "tests\\avg_out\\avg_shapes.txt"],
        cwd=CSRC, capture_output=True, text=True)
    sys.stdout.write(r.stdout)
    sys.stderr.write(r.stderr)
    return r.returncode == 0


def parse_c_output(path):
    """-> {name: (addr, stop, [(x0,y0,x1,y1,z,clip), ...])}"""
    shapes = {}
    with open(path) as f:
        lines = [ln.rstrip("\n") for ln in f]
    i = 0
    while i < len(lines):
        line = lines[i]
        if line.startswith("SHAPE "):
            parts = line.split()
            _, name, addrhex, nseg, stop = parts[0], parts[1], parts[2], parts[3], parts[4]
            nseg = int(nseg)
            segs = []
            for _k in range(nseg):
                i += 1
                segs.append(tuple(int(v) for v in lines[i].split()))
            shapes[name] = (int(addrhex, 16), stop, segs)
            i += 1  # END
        i += 1
    return shapes


def q15(v):
    q = v * 32768.0
    qi = int(round(q))
    if abs(q - qi) > 1e-6:
        raise AssertionError("non-integral Q15 value %r -> %r" % (v, q))
    return qi


def ref_segments(mem, addr):
    r = vrender.walk(mem, addr, max_steps=MAX_OPS)
    return [(q15(x0), q15(y0), q15(x1), q15(y1), z) for x0, y0, x1, y1, z in r["segs"]]


def main():
    if not os.path.exists(VECTOR_TABLES):
        print("missing %s - run disasm/gen_from_roms.py first" % VECTOR_TABLES)
        return 2
    if not os.path.exists(ROM_IMAGE):
        print("missing %s - run disasm/gen_from_roms.py first" % ROM_IMAGE)
        return 2

    entries = load_entries()
    write_index(entries, INDEX_PATH)
    print("wrote %s: %d shapes" % (INDEX_PATH, len(entries)))

    if not run_avgshapes():
        print("tests\\avgshapes.exe failed")
        return 2
    if not os.path.exists(OUT_PATH):
        print("missing %s (avgshapes.exe did not write it)" % OUT_PATH)
        return 2
    got = parse_c_output(OUT_PATH)

    mem = avg.load_image(ROM_IMAGE)

    nmatch = 0
    nsegs_compared = 0
    mismatches = []
    for name, addr in entries:
        c = got.get(name)
        if c is None:
            mismatches.append((name, addr, "C side produced no SHAPE record"))
            continue
        c_addr, c_stop, c_segs = c
        if c_addr != addr:
            mismatches.append((name, addr, "C side address $%04X != $%04X" % (c_addr, addr)))
            continue
        want = ref_segments(mem, addr)
        got_geo = [s[:5] for s in c_segs]
        nsegs_compared += len(want)
        if len(got_geo) != len(want):
            mismatches.append((name, addr, "%d segments, vrender.py has %d" %
                                (len(got_geo), len(want))))
            continue
        bad = None
        for i, (g, w) in enumerate(zip(got_geo, want)):
            if g != w:
                bad = (i, g, w)
                break
        if bad:
            i, g, w = bad
            mismatches.append((name, addr, "segment %d: c=%s vrender=%s" % (i, g, w)))
            continue
        nmatch += 1

    print("GATE V: %d pictures/characters compared, %d match, %d segments checked" %
          (len(entries), nmatch, nsegs_compared))
    for name, addr, why in mismatches:
        print("MISMATCH %-10s $%04X: %s" % (name, addr, why))

    ok = len(entries) > 0 and nmatch == len(entries)
    print("GATE V: %s" % ("PASS" if ok else "FAIL"))
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())
