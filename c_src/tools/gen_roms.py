#!/usr/bin/env python3
"""Generate the ROM images the Battlezone port and its reference harness link.

Adapted from the Tempest port's tools/gen_roms.py.  Inputs (already extracted
by ../disasm/gen_from_roms.py from the project's ROM survey - never
hand-transcribed):
  ../disasm/_survey/roms_extracted/bzone_cpu64k.bin   64K CPU image (ROM at
      $3000-$3FFF and $5000-$7FFF, the rest padded $FF; see disasm/STATUS.md)
  ../disasm/_survey/roms/bzone/036174-01.b1           Mathbox mapping PROM
  ../disasm/_survey/roms/bzone/036175-01.m1 .. 036180-01.f1   microcode

Outputs (c_src/):
  progrom.c/h   program ROM $5000-$7FFF  (progrom[addr - 0x5000])
  vecrom.c/h    vector ROM  $3000-$3FFF  (vecrom[addr - 0x3000])
  mbprom.c/h    Mathbox: mapping PROM (32 x 8) and the 256 x 24-bit microcode

The Mathbox is byte-identical hardware to Tempest's (MATHBOX_NOTES.md,
verified again here): mapping PROM 036174-01.b1 = Tempest's 136002-126.a1;
microcode 036175-01.m1..036180-01.f1 = Tempest's 136002-132.l1..127.e1 (note
the REVERSED part order - Battlezone's PROMs run high-nibble-first where
Tempest's run low-nibble-first).  This script verifies the byte-for-byte
match itself (not just cites MATHBOX_NOTES.md's CRC32s) before emitting.

Microcode nibble order (mathbox.c's interpreter, same word layout as
Tempest's): bit 23..0 = A(4) B(4) I2HI I2LO I1 I0 STALL I5..I3 LDAB I8..I6
SIGN JMP MULT CARIN.  The six 4-bit PROMs hold those nibbles low-first:
036180-01.f1 = bits 3-0, 036179-01.h1 = 7-4, 036178-01.j1 = 11-8,
036177-01.k1 = 15-12, 036176-01.l1 = 19-16, 036175-01.m1 = 23-20 (Tempest's
127.e1..132.l1 in the same low-to-high order).  Checked against the source
the same way Tempest's generator does: RSTO's "LDL 0 LDAB 16 JMP" (write AL,
uPC $20) is $1073B4 and RDISP's "OR Z,n NOP STALL" (uPC $10+n) is $0n3B10;
this script asserts both (identical microcode -> identical assertions).

Rerun:  python c_src/tools/gen_roms.py
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
CSRC = os.path.normpath(os.path.join(HERE, ".."))
ROOT = os.path.normpath(os.path.join(CSRC, ".."))
EXT = os.path.join(ROOT, "disasm", "_survey", "roms_extracted")
IMAGE = os.path.join(EXT, "bzone_cpu64k.bin")
PROMDIR = os.path.join(ROOT, "disasm", "_survey", "roms", "bzone")
MB_MAP = "036174-01.b1"
# low nibble (bits 3-0) first, matching Tempest's 127.e1..132.l1 order
MB_UCODE = ["036180-01.f1", "036179-01.h1", "036178-01.j1",
            "036177-01.k1", "036176-01.l1", "036175-01.m1"]
# Tempest's own PROMs, for the byte-identity check (MATHBOX_NOTES.md)
TEMPEST_PROMDIR = os.path.join(ROOT, "..", "Tempest Dissasembly", "disasm",
                                "_survey", "roms_extracted", "tempest3")
TEMPEST_MB_MAP = "136002-126.a1"
TEMPEST_MB_UCODE = ["136002-127.e1", "136002-128.f1", "136002-129.h1",
                     "136002-130.j1", "136002-131.k1", "136002-132.l1"]


def need(path):
    if not os.path.exists(path):
        sys.exit("gen_roms: missing %s (run disasm/gen_from_roms.py first)" % path)
    with open(path, "rb") as f:
        return f.read()


def emit_bytes(name, base, data, what):
    h = os.path.join(CSRC, name + ".h")
    c = os.path.join(CSRC, name + ".c")
    guard = name.upper() + "_H"
    with open(h, "w", encoding="utf-8", newline="\n") as f:
        f.write("/* %s.h - GENERATED by c_src/tools/gen_roms.py - do not edit. */\n" % name)
        f.write("#ifndef %s\n#define %s\n#include <stdint.h>\n" % (guard, guard))
        f.write("#define %s_BASE 0x%04X\n#define %s_SIZE 0x%04X\n"
                % (name.upper(), base, name.upper(), len(data)))
        f.write("extern const uint8_t %s[0x%04X]; /* %s */\n#endif\n" % (name, len(data), what))
    with open(c, "w", encoding="utf-8", newline="\n") as f:
        f.write("/* %s.c - GENERATED by c_src/tools/gen_roms.py from\n"
                " * ../disasm/_survey/roms_extracted/bzone_cpu64k.bin - do not edit.\n"
                " * %s, CPU $%04X-$%04X. */\n" % (name, what, base, base + len(data) - 1))
        f.write('#include "%s.h"\n\nconst uint8_t %s[0x%04X] = {\n' % (name, name, len(data)))
        for i in range(0, len(data), 16):
            row = ",".join("0x%02X" % b for b in data[i:i + 16])
            f.write("    %s, /* $%04X */\n" % (row, base + i))
        f.write("};\n")
    print("wrote %s.c/.h ($%04X, %d bytes)" % (name, base, len(data)))


def main():
    img = need(IMAGE)
    if len(img) != 0x10000:
        sys.exit("gen_roms: %s is not a 64K image" % IMAGE)
    vec = lambda a: img[a] | (img[a + 1] << 8)
    # 15-bit address decode: vectors live at $7FFA (HARDWARE_NOTES.md), not $FFFA
    if (vec(0x7FFA), vec(0x7FFC), vec(0x7FFE)) == (0, 0, 0):
        sys.exit("gen_roms: vectors at $7FFA are all zero - wrong image?")
    emit_bytes("progrom", 0x5000, img[0x5000:0x8000], "program ROM ($5000-$7FFF)")
    emit_bytes("vecrom", 0x3000, img[0x3000:0x4000], "vector ROM")

    mp = need(os.path.join(PROMDIR, MB_MAP))
    nib = [need(os.path.join(PROMDIR, n)) for n in MB_UCODE]
    if len(mp) != 32 or any(len(x) != 256 for x in nib):
        sys.exit("gen_roms: Mathbox PROM sizes wrong")

    # Verify byte-for-byte identity with Tempest's Mathbox PROMs (MATHBOX_NOTES.md
    # claims this from CRC32s; re-checked here directly, byte for byte).
    if os.path.exists(TEMPEST_PROMDIR):
        tmp = need(os.path.join(TEMPEST_PROMDIR, TEMPEST_MB_MAP))
        tnib = [need(os.path.join(TEMPEST_PROMDIR, n)) for n in TEMPEST_MB_UCODE]
        if mp != tmp:
            sys.exit("gen_roms: mapping PROM %s != Tempest's %s (expected byte-identical)"
                      % (MB_MAP, TEMPEST_MB_MAP))
        for bzf, tpf, bzd, tpd in zip(MB_UCODE, TEMPEST_MB_UCODE, nib, tnib):
            if bzd != tpd:
                sys.exit("gen_roms: microcode PROM %s != Tempest's %s (expected byte-identical)"
                          % (bzf, tpf))
        print("Mathbox PROM check: all 7 PROMs byte-identical to Tempest's "
              "(%s + %s) - reuse confirmed" % (MB_MAP, ", ".join(MB_UCODE)))
    else:
        print("Mathbox PROM check: SKIPPED (%s not found - Tempest tree not alongside)"
              % TEMPEST_PROMDIR)

    ucode = [sum((nib[k][i] & 0xF) << (4 * k) for k in range(6)) for i in range(256)]
    assert ucode[0x20] == 0x1073B4, "microcode nibble order check (RSTO AL) failed: %06X" % ucode[0x20]
    for n in range(16):
        if n != 6:   # RN's slot is the CLRNH jump, not a display
            assert ucode[0x10 + n] == 0x003B10 | (n << 16), "RDISP check failed at %d" % n
    h = os.path.join(CSRC, "mbprom.h")
    c = os.path.join(CSRC, "mbprom.c")
    with open(h, "w", encoding="utf-8", newline="\n") as f:
        f.write("/* mbprom.h - GENERATED by c_src/tools/gen_roms.py - do not edit. */\n"
                "#ifndef MBPROM_H\n#define MBPROM_H\n#include <stdint.h>\n"
                "extern const uint8_t  mb_map[32];     /* 036174-01.b1: write offset -> uPC */\n"
                "extern const uint32_t mb_ucode[256];  /* 036175..036180-01: 24-bit microcode */\n"
                "#endif\n")
    with open(c, "w", encoding="utf-8", newline="\n") as f:
        f.write("/* mbprom.c - GENERATED by c_src/tools/gen_roms.py from the Mathbox\n"
                " * PROMs 036174-01 (mapping) and 036175..036180-01 (microcode) - do not edit.\n"
                " * Byte-identical to Tempest's 136002-126..132 (MATHBOX_NOTES.md; verified\n"
                " * again by this script).  Word layout: see mathbox.c. */\n#include \"mbprom.h\"\n\n")
        f.write("const uint8_t mb_map[32] = {\n")
        for i in range(0, 32, 8):
            f.write("    %s,\n" % ",".join("0x%02X" % b for b in mp[i:i + 8]))
        f.write("};\n\nconst uint32_t mb_ucode[256] = {\n")
        for i in range(0, 256, 8):
            f.write("    %s, /* uPC $%02X */\n" % (",".join("0x%06X" % w for w in ucode[i:i + 8]), i))
        f.write("};\n")
    print("wrote mbprom.c/.h (32-byte map, 256 microcode words)")


if __name__ == "__main__":
    main()
