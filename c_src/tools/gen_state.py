#!/usr/bin/env python3
"""Generate state_defs.h (RAM symbol aliases) from ../disasm/bzone_defines.asm.

Adapted from the Tempest port's tools/gen_state.py (same defines-file layout:
";---[ Section ]---" markers, ".alias NAME $HEX ;comment" lines).  Differences
from Tempest:

  * RAM is $0000-$03FF (1 KB), not $0000-$07FF: RAM_END below.
  * Battlezone's variable sections are "Zero page variables" and "Game RAM"
    (no separate "Stack page" section - the 6502 stack $0100-$01FF is
    unnamed, inside "Game RAM").
  * Battlezone-specific requirement (PLAN.md M0 deliverable 1): tank/robot
    "twin" cells are indexed X=0/2 across neighbouring names (COLFLG/SAVE1,
    FIRECT/DQUE, TANGLE/NTHETA, OBJCOL/EIRNGE, SNDWRD/SAVE2+1, SHELLX/SHELLY/
    SINCX/SINCY, LANGLE, HITS ...).  Besides the scalar lvalue this generator
    also emits an indexable form, NAME_AT(i), that addresses the flat
    g.ram[] array at A_NAME+i with NO bounds tied to the cell's own declared
    size - so e.g. COLFLG_AT(2) reaches the same byte as SAVE1_AT(1)
    (COLFLG is 1 byte, SAVE1 is 2 bytes starting one byte later; COLFLG+2 ==
    SAVE1+1, exactly the robot's twin of the tank's COLFLG).  Emitted for
    every RAM cell, not just the documented twins, since the idiom
    (NAME,X with X=0/2) recurs throughout BZONE.MAC and a generic macro
    costs nothing extra.

Rules (same as Tempest):
  * every .alias outside "Constants" becomes an address constant
        #define A_NAME  0xADDR
  * aliases in the variable sections inside CPU RAM ($0000-$03FF) also
    become the cell as an lvalue and an indexable macro
        #define NAME       (g.ram[A_NAME])
        #define NAME_AT(i) (g.ram[(A_NAME + (i)) & 0x3FF])
  * "Constants" aliases are values, not addresses:
        #define K_NAME  0xVALUE

Region markers (Memory map), hardware registers, Vector RAM and Vector ROM
get the address constant only: translated code reaches hardware through the
hw_* seam and vector RAM/ROM through VRAM(A_NAME + i) / the ROM tables.

Rerun after regenerating the disassembly:   python c_src/tools/gen_state.py
"""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
CSRC = os.path.normpath(os.path.join(HERE, ".."))
ROOT = os.path.normpath(os.path.join(CSRC, ".."))
SRC = os.path.join(ROOT, "disasm", "bzone_defines.asm")
OUT = os.path.join(CSRC, "state_defs.h")

RAM_END = 0x0400                       # $0000-$03FF is CPU RAM (1 KB)
VAR_SECTIONS = ("Zero page variables", "Game RAM")
CONST_SECTION = "Constants"

SECTION_RE = re.compile(r"^;-*\[\s*(.*?)\s*\]-*$")
ALIAS_RE = re.compile(r"^\.alias\s+(\w+)\s+\$([0-9A-Fa-f]+)\s*(?:;(.*))?$")


def parse(path):
    """[(section, name, value, comment)] in file order."""
    out, section = [], ""
    with open(path, encoding="utf-8") as f:
        for raw in f:
            line = raw.strip()
            m = SECTION_RE.match(line)
            if m:
                section = m.group(1)
                continue
            m = ALIAS_RE.match(line)
            if m:
                out.append((section, m.group(1), int(m.group(2), 16),
                            (m.group(3) or "").strip()))
    return out


def ccomment(text):
    return text.replace("*/", "* /")


def main():
    if not os.path.exists(SRC):
        sys.exit("gen_state: missing %s" % SRC)
    aliases = parse(SRC)
    seen = set()
    nram = nconst = naddr = 0
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        w = f.write
        w("/* state_defs.h - GENERATED by c_src/tools/gen_state.py from\n"
          " * ../disasm/bzone_defines.asm - do not edit by hand.\n"
          " *\n"
          " * A_NAME = CPU address of an alias.  NAME = the RAM cell as an lvalue\n"
          " * (variable sections only).  NAME_AT(i) = the same cell, indexable with\n"
          " * NO per-cell bounds (A_NAME+i on the flat g.ram[] array) - for the\n"
          " * tank/robot twin-cell idiom (NAME,X with X=0/2; see gen_state.py's\n"
          " * header).  K_NAME = a Constants-section value.\n"
          " * Vector RAM: VRAM(A_NAME + i).  Hardware: hw_* (hw.h). */\n\n")
        w("#ifndef STATE_DEFS_H\n#define STATE_DEFS_H\n")
        cur = None
        for sec, name, val, cmt in aliases:
            if sec != cur:
                w("\n/* ---- %s ---- */\n" % sec)
                cur = sec
            if name in seen:
                w("/* duplicate alias %s = $%X skipped */\n" % (name, val))
                continue
            seen.add(name)
            c = ("  /* %s */" % ccomment(cmt)) if cmt else ""
            if sec == CONST_SECTION:
                w("#define K_%-12s 0x%02X%s\n" % (name, val, c))
                nconst += 1
                continue
            w("#define A_%-12s 0x%04X%s\n" % (name, val, c))
            naddr += 1
            if sec in VAR_SECTIONS and val < RAM_END:
                w("#define %-14s (g.ram[A_%s])\n" % (name, name))
                w("#define %s_AT(i)  (g.ram[(A_%s + (i)) & 0x3FF])\n" % (name, name))
                nram += 1
        w("\n#endif /* STATE_DEFS_H */\n")
    print("wrote %s (%d addresses, %d RAM cells, %d constants)"
          % (os.path.normpath(OUT), naddr, nram, nconst))


if __name__ == "__main__":
    main()
